#!/usr/bin/env node
// Builds types/index.d.ts from the describe() metadata of every exported component, so props are documented once.
// Prop types in describe() are short TypeScript-like strings; one that does not parse as a type becomes `any`.
//
//   node tools/build-types.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lib = await import(join(root, 'src', 'index.js'));

const parses = (type) => {
  const sf = ts.createSourceFile('t.ts', `type T = ${type};`, ts.ScriptTarget.Latest);
  return sf.parseDiagnostics.length === 0;
};
// `(value) => void` -> `(value: any) => void`: describe() leaves obvious parameter types out.
const typed = (type) => type.replace(/\(([^()]*)\)\s*=>/g, (all, params) => `(${params.split(',').map((p) => (p.trim() && !p.includes(':') && /^\w+$/.test(p.trim()) ? `${p.trim()}: any` : p)).join(',')}) =>`);
// `{ start, end }` -> `{ start: any; end: any }`, `{ navigateTo(date) }` -> `{ navigateTo(date: any): any }`
const members = (type) => type
  .replace(/(\w+)\(([^()]*)\)(?=\s*[;,}])/g, (all, name, params) => `${name}(${params.split(',').map((p) => (/^\s*\w+\s*$/.test(p) ? `${p.trim()}: any` : p)).join(',')}): any`)
  .replace(/([{;,]\s*)(\w+)(\??)(\s*)(?=[;,}])/g, (all, pre, name, opt, sp) => `${pre}${name}${opt}: any${sp}`);
const clean = (type) => {
  const t = members(typed(type.replace(/,?\s*…/g, '')).replace(/pixel\(\)|proportional\(\)/g, 'number').replace(/^RefObject\b(?!<)/, 'RefObject<any>').replace(/^function$/, '(...args: any[]) => any').replace(/\bfunction\b/, '((...args: any[]) => any)'));
  return parses(t) ? t : 'any';
};
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

const out = [
  '// Generated by tools/build-types.mjs from describe() in src/components. Do not edit.',
  "import type { ReactNode, ReactElement, Ref, RefObject, ElementType, ComponentType } from 'react';",
  '',
  'export type ISODateString = string;',
  '',
];
for (const [name, value] of Object.entries(lib).sort(([a], [b]) => a.localeCompare(b))) {
  const info = value && value.__docgenInfo;
  if (!/^[A-Z]/.test(name) || typeof value !== 'function') {
    if (typeof value === 'function') out.push(`export function ${name}(...args: any[]): any;`);
    continue;
  }
  if (!info) { out.push(`export const ${name}: ComponentType<any>;`); continue; }
  const props = Object.entries(info.props).map(([prop, p]) => {
    const doc = [p.description, p.defaultValue ? `@default ${p.defaultValue.value}` : ''].filter(Boolean).map((l) => ` * ${l.replace(/\*\//g, '* /')}`).join('\n');
    return `  /**\n${doc}\n   */\n  ${key(prop)}?: ${clean(p.tsType.name)};`.replace(/^ \*/gm, '   *');
  });
  out.push(`export interface ${name}Props {`, ...props, ...(info.props.children ? [] : ['  children?: ReactNode;']), '  [dataAttribute: `data-${string}`]: string | number | boolean | undefined;', '  [ariaAttribute: `aria-${string}`]: string | number | boolean | undefined;', '}');
  out.push(`/** ${(info.description || '').replace(/\*\//g, '* /')} */`, `export function ${name}(props: ${name}Props): ReactElement | null;`, '');
}
await mkdir(join(root, 'types'), { recursive: true });
await writeFile(join(root, 'types', 'index.d.ts'), `${out.join('\n')}\n`);
console.log(`types/index.d.ts: ${Object.keys(lib).length} exports`);
