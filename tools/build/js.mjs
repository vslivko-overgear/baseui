#!/usr/bin/env node
// Compiles every .jsx source next to itself into a .js module (automatic JSX runtime, relative imports renamed .jsx -> .js).
// The documentation site, the examples and the package serve the .js files; they are not committed.
//
//   node tools/build/js.mjs            # build
//   node tools/build/js.mjs --watch    # rebuild on change
import { readdir, readFile, writeFile, watch } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { transform } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const roots = ['src', 'site', 'overgear'];

async function* walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (e.name.endsWith('.jsx')) yield p;
  }
}

export async function build(file) {
  const src = await readFile(file, 'utf8');
  const { code } = await transform(src, { loader: 'jsx', jsx: 'automatic', format: 'esm', target: 'es2022', sourcefile: file });
  await writeFile(file.replace(/\.jsx$/, '.js'), code.replace(/(['"`])(\.{1,2}\/[^'"`]*?)\.jsx\1/g, '$1$2.js$1'));
}

const files = [];
for (const r of roots) for await (const f of walk(join(root, r))) files.push(f);
await Promise.all(files.map(build));
console.log(`${files.length} .jsx -> .js`);

// keep the generated files out of git: one block of .gitignore, rewritten here
const ignore = files.map((f) => f.slice(root.length + 1).replace(/\.jsx$/, '.js')).sort();
const gi = join(root, '.gitignore');
const base = (await readFile(gi, 'utf8').catch(() => '')).replace(/\n?# generated by tools\/build-js\.mjs[\s\S]*$/, '').trimEnd();
await writeFile(gi, `${base}\n\n# generated by tools/build/js.mjs\n${ignore.join('\n')}\n`);

if (process.argv.includes('--watch')) {
  for (const r of roots) {
    (async () => {
      for await (const ev of watch(join(root, r), { recursive: true })) {
        if (ev.filename?.endsWith('.jsx')) { await build(join(root, r, ev.filename)).catch((e) => console.error(e.message)); console.log('rebuilt', ev.filename); }
      }
    })();
  }
}
